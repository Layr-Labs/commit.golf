#!/usr/bin/env python3
"""Generate a local development module; official verification regenerates its own."""
from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import re
import stat
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'verifier'))
from artifact import load_artifact, purge_artifact_cache

HEADER = (b'-- Local artifact generated by scripts/generate_artifact.py.\n'
          b'-- Development only; the verifier regenerates its own artifact.\n')
METADATA = re.compile(rb'-- Manifest SHA-256: ([0-9a-f]{64})\n'
                      rb'-- Generated-body SHA-256: ([0-9a-f]{64})\n\n')
MAX_LOCAL_SOURCE_BYTES = 32 * 1024 * 1024


def ordinary_directory(path: Path):
    """Reject linked parents before writing a source or invalidating local caches."""
    if not stat.S_ISDIR(path.lstat().st_mode):
        raise ValueError(f'expected an ordinary directory, without symlinks: {path}')


def check_cache_paths(project: Path):
    for suffix in ('lib/lean/CommitGolf', 'ir/CommitGolf'):
        folder = project
        for component in ('.lake', 'build', *suffix.split('/')):
            folder /= component
            try:
                ordinary_directory(folder)
            except FileNotFoundError:
                break
        else:
            for cached in folder.glob('Artifact.*'):
                mode = cached.lstat().st_mode
                if not (stat.S_ISREG(mode) or stat.S_ISLNK(mode)):
                    raise ValueError(f'refusing to remove non-file cache entry: {cached}')


def existing_source(destination: Path) -> bytes | None:
    try:
        mode = destination.lstat().st_mode
    except FileNotFoundError:
        return None
    if not stat.S_ISREG(mode):
        raise ValueError(f'refusing to replace a non-regular file: {destination}')
    flags = os.O_RDONLY | os.O_NONBLOCK | getattr(os, 'O_NOFOLLOW', 0)
    with os.fdopen(os.open(destination, flags), 'rb') as source:
        if not stat.S_ISREG(os.fstat(source.fileno()).st_mode):
            raise ValueError(f'refusing to read a non-regular file: {destination}')
        previous = source.read(MAX_LOCAL_SOURCE_BYTES + 1)
    if len(previous) > MAX_LOCAL_SOURCE_BYTES or not previous.startswith(HEADER):
        raise ValueError('Artifact.lean is not a managed local file; move it aside first')
    metadata = METADATA.match(previous, len(HEADER))
    if metadata is None or hashlib.sha256(previous[metadata.end():]).hexdigest().encode() != metadata[2]:
        raise ValueError('Artifact.lean was edited or has invalid metadata; move it aside first')
    return previous


def generate(manifest: Path, project: Path, refresh: bool = False) -> tuple[str, str]:
    artifact = load_artifact(manifest)
    # The renderer is shared verbatim with verification; only fixed metadata comments are added.
    body = artifact.lean_source().encode('utf-8')
    rendered = (HEADER + f'-- Manifest SHA-256: {artifact.digest}\n'
                f'-- Generated-body SHA-256: {hashlib.sha256(body).hexdigest()}\n\n'.encode() + body)
    contract = project / 'CommitGolf'
    ordinary_directory(contract)
    destination = contract / 'Artifact.lean'
    previous = existing_source(destination)
    if previous == rendered and destination.lstat().st_mode & 0o777 == 0o644:
        return 'Already current', artifact.digest
    if previous is not None and previous != rendered and not refresh:
        raise ValueError('Artifact.lean differs from this manifest; rerun with --refresh')
    check_cache_paths(project)
    descriptor, temporary = tempfile.mkstemp(prefix='.Artifact.', suffix='.tmp', dir=contract)
    temporary = Path(temporary)
    try:
        with os.fdopen(descriptor, 'wb') as source:
            source.write(rendered)
            # The verifier copies this file, then overwrites it with its authoritative module.
            os.fchmod(source.fileno(), 0o644)
        purge_artifact_cache(project)
        os.replace(temporary, destination)
    finally:
        temporary.unlink(missing_ok=True)
    return 'Refreshed' if previous is not None else 'Generated', artifact.digest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, epilog=(
        'Defaults are relative to this repository, independent of the working directory. '
        'Build with lake build CommitGolf.Artifact. This command does not verify or score a submission.'))
    parser.add_argument('manifest', nargs='?', type=Path, default=ROOT / 'submission/programs.json',
                        help='delivered programs.json (default: repository submission/programs.json)')
    parser.add_argument('--refresh', action='store_true',
                        help='replace an unedited generated module and invalidate Artifact.* caches')
    args = parser.parse_args()
    try:
        action, digest = generate(args.manifest, ROOT, args.refresh)
    except (OSError, ValueError) as error:
        parser.exit(1, f'{parser.prog}: {error}\n')
    print(f'{action}: {ROOT / "CommitGolf/Artifact.lean"}\nManifest SHA-256: {digest}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
